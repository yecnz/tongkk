import { describe, expect, it } from 'vitest';
import { cleanSummary } from './summaryValidator';

describe('cleanSummary', () => {
  it('구간 경계에서 반복된 제목·문단, 빈 섹션, 닫히지 않은 코드 블록을 정리한다', () => {
    const input = [
      '# 1장 운영체제',
      '## 프로세스',
      '프로세스는 실행 중인 프로그램이다.',
      '',
      '## 프로세스',
      '',
      '**프로세스**는  실행 중인 프로그램이다.',
      '',
      '- PCB에 상태를 저장한다.',
      '',
      '## 빈 섹션',
      '',
      '## 스레드',
      '### 정의',
      '---',
      '---',
      '',
      '```c',
      'fork();',
    ].join('\n');

    expect(cleanSummary(input)).toBe([
      '# 1장 운영체제',
      '## 프로세스',
      '프로세스는 실행 중인 프로그램이다.',
      '- PCB에 상태를 저장한다.',
      '## 스레드',
      '### 정의',
      '---\n---',
      '```c\nfork();\n```',
    ].join('\n\n'));
  });

  it('다른 섹션 아래 같은 소제목은 남기고, 표·코드 블록 안 빈 줄은 건드리지 않는다', () => {
    const input = [
      '## A',
      '### 핵심 개념',
      '내용 A는 이런 것이다.',
      '## B',
      '### 핵심 개념',
      '내용 B는 저런 것이다.',
      '',
      '| 항목 | 설명 |',
      '| --- | --- |',
      '| x | y |',
      '',
      '```',
      'a',
      '',
      'b',
      '```',
    ].join('\n');

    expect(cleanSummary(input)).toBe([
      '## A',
      '### 핵심 개념',
      '내용 A는 이런 것이다.',
      '## B',
      '### 핵심 개념',
      '내용 B는 저런 것이다.',
      '| 항목 | 설명 |\n| --- | --- |\n| x | y |',
      '```\na\n\nb\n```',
    ].join('\n\n'));
  });

  it('다른 섹션의 같은 수식, 이름이 같은 다른 수준 제목, 들여쓴 하위 bullet은 지우지 않는다', () => {
    const input = [
      '## 동적 프로그래밍',
      '### 동적 프로그래밍',
      '- **예시/적용 맥락**',
      '',
      '  - 자료에서 구체적인 예시는 제시되지 않음',
      '',
      '$$T(n)=2T(n/2)+n$$',
      '### 메모이제이션',
      '- **예시/적용 맥락**',
      '',
      '  - 자료에서 구체적인 예시는 제시되지 않음',
      '',
      '$$T(n)=2T(n/2)+n$$',
    ].join('\n');

    expect(cleanSummary(input)).toBe(input.replace(/\n+/g, '\n\n'));
  });
});
